export function guestSteps(sprite: number, body: HTMLImageElement | HTMLCanvasElement) {
  const split = feet[sprite];
  const { width, height } = body;
  const hem = split?.[0][1] ?? height;
  const waist = Math.min(232, hem - 20);
  const legs: { clip: Path2D; side: number }[] = [];
  if (split) {
    for (const side of [-1, 1]) {
      const edge = side < 0 ? 0 : width;
      const clip = new Path2D();
      clip.moveTo(edge, hem - 2);
      clip.lineTo(split[0][0], hem - 2);
      for (const [x, y] of split) clip.lineTo(x, y);
      clip.lineTo(split[split.length - 1][0], height);
      clip.lineTo(edge, height);
      clip.closePath();
      legs.push({ clip, side });
    }
  }

  return function draw(ctx: CanvasRenderingContext2D, stride: number) {
    if (!stride) {
      ctx.drawImage(body, 0, 0);
      return;
    }
    // Adjacent transforms meet along these two horizontal joints. Cover the
    // subpixel antialiasing fringe where independently rasterized pieces meet.
    ctx.drawImage(body, 0, 0, width, waist + 2, 0, 0, width, waist + 2);
    const hemSwing = stride * (split ? 2 : 6);
    ctx.save();
    ctx.translate(0, waist);
    ctx.transform(1, 0, hemSwing / (hem - waist), 1, 0, 0);
    const skirtEnd = Math.min(height, hem + 2);
    ctx.drawImage(body, 0, waist, width, skirtEnd - waist, 0, 0, width, skirtEnd - waist);
    ctx.restore();
    for (const { side, clip } of legs) {
      const step = side * stride;
      const swing = Math.min(10, (height - hem) * .20);
      const lift = Math.min(5, (height - hem) * .085) * Math.max(0, step);
      ctx.save();
      ctx.translate(hemSwing, hem);
      ctx.transform(1, 0, step * swing / (height - hem), 1 - lift / (height - hem), 0, 0);
      ctx.translate(0, -hem);
      ctx.clip(clip);
      ctx.drawImage(body, 0, 0);
      ctx.restore();
    }
  };
}
